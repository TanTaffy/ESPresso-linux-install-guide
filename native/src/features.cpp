std::string loop_parameters(const json &t, const std::map<std::string, json> &data)
{
    if (t.value("trigger", "periodic") == "queues")
        return "const Event& event";
    if (t.value("trigger", "periodic") != "queue")
        return "";
    return "const " + data.at(t.at("queueId")).at("typeName").get<std::string>() + "& event";
}

Files queue_files(const json &s, const json &project)
{
    const std::string sym = s["symbol"], tn = s["typeName"];
    // The typed data definition is shared with snapshot structs; replace only the helper API.
    const std::string header =
        "#include \"freertos/FreeRTOS.h\"\n\nnamespace espresso::shared {\nesp_err_t init_" + sym +
        "();\nbool send_" + sym + "(const data::" + tn +
        "& value, TickType_t timeout);\nbool receive_" + sym + "(data::" + tn +
        "& value, TickType_t timeout);\n}\n";
    std::string source =
        "#include \"" + sym +
        ".hpp\"\n#include \"freertos/queue.h\"\n#include "
        "\"generated/project_headers.hpp\"\n\nnamespace {\nQueueHandle_t queue = "
        "nullptr;\n}\n\nnamespace espresso::shared {\nesp_err_t init_" +
        sym + "()\n{\n    if (queue != nullptr) return ESP_ERR_INVALID_STATE;\n    " +
        (s.value("delivery", "queue") == "mailbox"
             ? ""
             : "static_assert(::" + queue_namespace(s) +
                   "::CAPACITY >= 1 && ::" + queue_namespace(s) +
                   "::CAPACITY <= 4096, \"Queue capacity must be 1-4096\");\n    ") +
        "queue = xQueueCreate(" +
        (s.value("delivery", "queue") == "mailbox" ? std::string("1")
                                                   : "::" + queue_namespace(s) + "::CAPACITY") +
        ", sizeof(data::" + tn +
        "));\n    return queue != nullptr ? ESP_OK : ESP_ERR_NO_MEM;\n}\n\nbool send_" + sym +
        "(const data::" + tn +
        "& value, TickType_t timeout)\n{\n    configASSERT(queue != nullptr);\n    return "
        "xQueueSend(queue, &value, timeout) == pdTRUE;\n}\n\nbool receive_" +
        sym + "(data::" + tn +
        "& value, TickType_t timeout)\n{\n    configASSERT(queue != nullptr);\n    return "
        "xQueueReceive(queue, &value, timeout) == pdTRUE;\n}\n}\n";
    const std::string call = "xQueueSend(queue, &value, timeout) == pdTRUE";
    const bool mailbox = s.value("delivery", "queue") == "mailbox";
    std::string send =
        mailbox ? "    (void)timeout; // A mailbox replaces the unread value without blocking.\n   "
                  " const bool sent = xQueueOverwrite(queue, &value) == pdTRUE;\n"
                : "    const bool sent = " + call + ";\n";
    if (multi_watches(project, s["id"]))
    {
        source = "#include \"generated/data_signals.hpp\"\n" + source;
        send += "    if (sent) ::espresso::generated::signal_" + sym + "();\n";
    }
    source.replace(source.find("    return " + call + ";"), ("    return " + call + ";").size(),
                   send + "    return sent;");
    return {{"header", header}, {"source", source}};
}

std::string event_runtime(const std::vector<json> &tasks, const std::map<std::string, json> &data)
{
    std::string out =
        "// Generated by ESPresso.\n#include \"task_runtime.hpp\"\n#include "
        "\"freertos/FreeRTOS.h\"\n#include \"freertos/task.h\"\n#include "
        "\"freertos/event_groups.h\"\n#include \"freertos/semphr.h\"\n#include "
        "\"project_headers.hpp\"\n#include \"data_signals.hpp\"\n#include \"esp_err.h\"\n";
    for (const auto &t : tasks)
        out += "#include \"tasks/" + t["symbol"].get<std::string>() + "_task.hpp\"\n";
    for (const auto &[id, q] : data)
        out += "#include \"shared/" + q["symbol"].get<std::string>() + ".hpp\"\n";
    out += "\nnamespace {\nEventGroupHandle_t started = nullptr;\nnamespace handles {\n";
    for (const auto &t : tasks)
        out += "TaskHandle_t " + t["symbol"].get<std::string>() + " = nullptr;\n";
    out += "}\n";
    for (const auto &t : tasks)
        if (t.value("trigger", "periodic") == "queues")
            out += "SemaphoreHandle_t wake_" + t["symbol"].get<std::string>() + " = nullptr;\n";
    for (const auto &t : tasks)
    {
        const std::string sym = t["symbol"], trigger = t.value("trigger", "periodic");
        out += "\nvoid " + sym +
               "_entry(void *)\n{\n    // All task handles exist before setup can send "
               "notifications.\n    xEventGroupWaitBits(started, BIT0, pdFALSE, pdTRUE, "
               "portMAX_DELAY);\n    espresso::tasks::" +
               sym + "::setup();\n";
        if (trigger == "periodic")
            out += "    constexpr auto period_ms = ::" + config_namespace(t) + "::PERIOD_MS" +
                   ";\n    static_assert(period_ms > 0 && period_ms <= 3600000, \"Period must be "
                   "1-3600000 ms\");\n    constexpr TickType_t period = pdMS_TO_TICKS(period_ms" +
                   ");\n    static_assert(period > 0, \"Task period is below one FreeRTOS "
                   "tick\");\n    TickType_t last_wake = "
                   "xTaskGetTickCount();\n";
        if (trigger == "queues")
            out += "    size_t next_input = 0;\n";
        out += "    while (true) {\n";
        if (trigger == "notification")
            out += "        // Consume one counting notification for each loop invocation.\n       "
                   " ulTaskNotifyTake(pdFALSE, portMAX_DELAY);\n";
        if (trigger == "queue")
        {
            const auto &q = data.at(t.at("queueId"));
            out += "        espresso::data::" + q["typeName"].get<std::string>() +
                   " event{};\n        if (espresso::shared::receive_" +
                   q["symbol"].get<std::string>() +
                   "(event, portMAX_DELAY))\n            espresso::tasks::" + sym +
                   "::loop(event);\n";
        }
        else if (trigger == "queues")
        {
            const auto ids = trigger_ids(t);
            out += "        bool received = false;\n        for (size_t offset = 0; offset < " +
                   std::to_string(ids.size()) +
                   "; ++offset) {\n            const size_t input = (next_input + offset) % " +
                   std::to_string(ids.size()) + ";\n            switch (input) {\n";
            for (size_t i = 0; i < ids.size(); ++i)
            {
                const auto &q = data.at(ids[i]);
                const std::string qs = q["symbol"], tn = q["typeName"];
                out += "            case " + std::to_string(i) +
                       ": {\n                espresso::data::" + tn +
                       " value{};\n                if (espresso::shared::receive_" + qs +
                       "(value, 0)) {\n                    next_input = (input + 1) % " +
                       std::to_string(ids.size()) +
                       ";\n                    espresso::tasks::" + sym +
                       "::loop(espresso::tasks::" + sym + "::Event{espresso::tasks::" + sym +
                       "::" + qs +
                       "Event{value}});\n                    received = true;\n                }\n "
                       "               break;\n            }\n";
            }
            out += "            }\n            if (received) break;\n        }\n        if "
                   "(!received) xSemaphoreTake(wake_" +
                   sym + ", portMAX_DELAY);\n";
        }
        else
            out += "        espresso::tasks::" + sym + "::loop();\n";
        if (trigger == "periodic")
            out += "        vTaskDelayUntil(&last_wake, period);\n";
        out += "    }\n}\n";
    }
    out += "}\n\nnamespace espresso::generated {\n";
    out += "void init_shared()\n{\n";
    for (const auto &[id, q] : data)
        out += "    ESP_ERROR_CHECK(espresso::shared::init_" + q["symbol"].get<std::string>() +
               "());\n";
    out += "}\n\n";
    for (const auto &t : tasks)
        if (t.value("trigger", "periodic") == "notification")
        {
            const std::string sym = t["symbol"];
            out += "void notify_" + sym + "()\n{\n    configASSERT(handles::" + sym +
                   " != nullptr);\n    xTaskNotifyGive(handles::" + sym + ");\n}\n";
        }
    for (const auto &[id, q] : data)
    {
        std::string signals;
        for (const auto &t : tasks)
            if (t.value("trigger", "periodic") == "queues")
                for (const auto &input : trigger_ids(t))
                    if (input == id)
                        signals += "    if (wake_" + t["symbol"].get<std::string>() +
                                   " != nullptr) xSemaphoreGive(wake_" +
                                   t["symbol"].get<std::string>() + ");\n";
        if (!signals.empty())
            out += "void signal_" + q["symbol"].get<std::string>() + "()\n{\n" + signals + "}\n";
    }
    out += "void start_tasks()\n{\n    started = xEventGroupCreate();\n    ESP_ERROR_CHECK(started "
           "!= nullptr ? ESP_OK : ESP_ERR_NO_MEM);\n";
    for (const auto &t : tasks)
        if (t.value("trigger", "periodic") == "queues")
        {
            const std::string sym = t["symbol"];
            out += "    wake_" + sym + " = xSemaphoreCreateBinary();\n    ESP_ERROR_CHECK(wake_" +
                   sym + " != nullptr ? ESP_OK : ESP_ERR_NO_MEM);\n";
        }
    for (const auto &t : tasks)
    {
        const std::string sym = t["symbol"], scope = "::" + config_namespace(t) + "::";
        out += "    {\n        constexpr auto stack_bytes = " + scope +
               "STACK_BYTES;\n        constexpr auto priority = " + scope +
               "PRIORITY;\n        constexpr auto core = " + scope +
               "CORE_AFFINITY == -1 ? tskNO_AFFINITY : " + scope +
               "CORE_AFFINITY;\n        static_assert(stack_bytes >= 1024 && stack_bytes <= "
               "1048576 && stack_bytes % 4 == 0, \"Stack must be aligned and 1024-1048576 "
               "bytes\");\n        static_assert(priority >= 1 && priority <= 24, \"Priority must "
               "be 1-24\");\n        static_assert(core == tskNO_AFFINITY || (core >= 0 && core < "
               "configNUMBER_OF_CORES), \"Core affinity is unavailable on this target\");\n        "
               "ESP_ERROR_CHECK(xTaskCreatePinnedToCore(" +
               sym + "_entry, " + t["name"].dump(-1, ' ', false) +
               ", stack_bytes, nullptr, priority, &handles::" + sym +
               ", core) == pdPASS ? ESP_OK : ESP_ERR_NO_MEM);\n    }\n";
    }
    out += "    xEventGroupSetBits(started, BIT0);\n}\n}\n";
    return out;
}
